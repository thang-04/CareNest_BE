ALTER TABLE notifications ADD COLUMN push_initialized_at TIMESTAMPTZ;

CREATE TABLE notification_push_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    device_id BIGINT NOT NULL,
    state VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    last_error_kind VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notification_push_delivery UNIQUE (notification_id, device_id),
    CONSTRAINT ck_notification_delivery_state CHECK (state IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_notification_delivery_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_notification_delivery_completion CHECK (
        (state = 'PENDING' AND completed_at IS NULL)
        OR (state <> 'PENDING' AND completed_at IS NOT NULL AND next_attempt_at IS NULL)
    )
);

CREATE INDEX idx_notification_delivery_parent
    ON notification_push_deliveries (notification_id, state, next_attempt_at, id);
