-- G94-386: hàng chờ email cho thông báo kế hoạch giáo dục; mỗi thông báo (1 người nhận × 1 sự kiện) tối đa 1 email.
-- Dòng tạo cùng giao dịch với thông báo nên rollback nghiệp vụ không phát sinh email; worker gửi sau commit.
CREATE TABLE notification_email_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    scope VARCHAR(300),
    state VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    last_error_kind VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notification_email_delivery UNIQUE (notification_id),
    CONSTRAINT ck_notification_email_state CHECK (state IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_notification_email_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_notification_email_completion CHECK (
        (state = 'PENDING' AND completed_at IS NULL)
        OR (state <> 'PENDING' AND completed_at IS NOT NULL AND next_attempt_at IS NULL)
    )
);

CREATE INDEX idx_notification_email_due
    ON notification_email_deliveries (next_attempt_at, id)
    WHERE state = 'PENDING';
