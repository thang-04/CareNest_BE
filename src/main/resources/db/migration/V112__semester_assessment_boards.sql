CREATE TABLE semester_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 classroom_id BIGINT NOT NULL REFERENCES classrooms(id), campus_id BIGINT NOT NULL REFERENCES campuses(id),
 school_year_id BIGINT NOT NULL REFERENCES school_years(id), semester_no INTEGER NOT NULL CHECK(semester_no IN (1,2)),
 period_start DATE NOT NULL, period_end DATE NOT NULL, note VARCHAR(1000), result_snapshot TEXT,
 confirmed_by BIGINT REFERENCES user_accounts(id), confirmed_at TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_semester_assessment_class_period UNIQUE(classroom_id,semester_no),
 CONSTRAINT ck_semester_assessment_dates CHECK(period_start <= period_end),
 CONSTRAINT ck_semester_assessment_confirmation CHECK((confirmed_at IS NULL AND confirmed_by IS NULL AND result_snapshot IS NULL) OR (confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL AND result_snapshot IS NOT NULL))
);
