-- Bản cân đối khẩu phần của một ngày cho cả trường: lần 1 theo số trẻ dự kiến, lần 2 theo suất đã chốt
CREATE TABLE day_balances (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    balance_date  DATE        NOT NULL,
    round         SMALLINT    NOT NULL,
    rounding_step NUMERIC(4, 2),
    row_version   BIGINT      NOT NULL DEFAULT 0,
    saved_by      BIGINT      NOT NULL REFERENCES user_accounts (id),
    saved_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_day_balances_date_round UNIQUE (balance_date, round),
    CONSTRAINT ck_day_balances_round CHECK (round IN (1, 2)),
    CONSTRAINT ck_day_balances_step CHECK (rounding_step IS NULL OR rounding_step > 0)
);

CREATE TABLE day_balance_counts (
    day_balance_id BIGINT  NOT NULL REFERENCES day_balances (id) ON DELETE CASCADE,
    campus_id      BIGINT  NOT NULL REFERENCES campuses (id),
    age_group_id   BIGINT  NOT NULL REFERENCES age_groups (id),
    children       INTEGER NOT NULL,
    PRIMARY KEY (day_balance_id, campus_id, age_group_id),
    CONSTRAINT ck_day_balance_counts_children CHECK (children >= 0)
);

-- Gam ăn một trẻ theo món; tỷ lệ thải bỏ, giá và đơn vị mua chụp tại lúc lưu
CREATE TABLE day_balance_lines (
    day_balance_id     BIGINT         NOT NULL REFERENCES day_balances (id) ON DELETE CASCADE,
    age_group_id       BIGINT         NOT NULL REFERENCES age_groups (id),
    session            VARCHAR(20)    NOT NULL,
    dish_id            BIGINT         NOT NULL REFERENCES dishes (id),
    food_id            BIGINT         NOT NULL REFERENCES foods (id),
    base_grams         NUMERIC(14, 6) NOT NULL,
    grams              NUMERIC(14, 6) NOT NULL,
    waste_pct          NUMERIC(5, 2),
    unit_price         NUMERIC(14, 2),
    purchase_unit      VARCHAR(50),
    purchase_unit_size NUMERIC(14, 3),
    PRIMARY KEY (day_balance_id, age_group_id, session, dish_id, food_id),
    CONSTRAINT ck_day_balance_lines_grams CHECK (base_grams >= 0 AND grams >= 0)
);
